import { readFile, writeFile } from 'node:fs/promises';
// Generate only into a new, empty migration created by the Supabase CLI.
const filename=process.argv[2];
if(!/^\d{14}_[a-z0-9_]+\.sql$/.test(filename||'')) throw new Error('Pass the filename of a new migration created with supabase migration new.');
const target = new URL(`../supabase/migrations/${filename}`, import.meta.url);
if((await readFile(target,'utf8')).trim()) throw new Error('Refusing to overwrite a populated migration. Create a new migration first.');
const parts = await Promise.all(['crm-functions.sql', 'worker-functions.sql','runtime-hardening.sql'].map(name => readFile(new URL(`../supabase/sql/${name}`, import.meta.url), 'utf8')));
let sql=parts.join('\n').replaceAll('create function ','create or replace function ');
// Publication membership was established in the baseline; re-adding tables would fail.
sql=sql.replace(/do \$\$ declare t text; begin[\s\S]*?end \$\$;/g,'');
await writeFile(target, `-- Generated by scripts/assemble-migration.js from supabase/sql/.\n${sql}\n`);
