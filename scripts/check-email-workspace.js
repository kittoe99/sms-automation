import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const module=process.env.EMAIL_PLAYWRIGHT_MODULE;
const {chromium}=await import(module?pathToFileURL(module).href:'playwright');
const browser=await chromium.launch({headless:true,...(process.env.EMAIL_BROWSER_EXECUTABLE?{executablePath:process.env.EMAIL_BROWSER_EXECUTABLE}:{})});
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const failures=[];page.on('pageerror',e=>failures.push(e.message));
 await page.goto('http://127.0.0.1:8194');
 await page.locator('[data-starter]').selectOption('0');
 await page.getByRole('button',{name:'Publish saved draft',exact:true}).click();
 await page.getByRole('button',{name:/Enquiry follow-up · v1/}).waitFor();
 await page.locator('[data-subject]').first().fill('Welcome {{firstName}}');
 await page.getByRole('button',{name:'Preview saved or edited draft',exact:true}).click();
 await page.frameLocator('iframe').first().getByText('Your business',{exact:true}).first().waitFor();
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByRole('button',{name:'Publish saved draft',exact:true}).click();
 await page.getByRole('button',{name:/Enquiry follow-up · v2/}).waitFor();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByLabel('Reply-to mailbox').fill('owner@example.test');
 await page.getByLabel('Business mailing address').fill('123 Main Street, Denver, CO 80201');
 await page.getByLabel('Enable email sending for this business').check();
 await page.getByRole('button',{name:'Save sender settings',exact:true}).click();
 await page.getByRole('button',{name:'Activity',exact:true}).click();
 await page.getByText('Record existing email consent',{exact:true}).click();
 await page.getByLabel('Evidence',{exact:true}).fill('Customer signed email consent on an intake card');
 await page.getByLabel('Customer has given email marketing consent').check();
 await page.getByRole('button',{name:'Record choice',exact:true}).click();
 await page.locator('[data-start] select[name=contactId] option').filter({hasText:'consented'}).waitFor({state:'attached'});
 await page.getByRole('button',{name:'Start sequence',exact:true}).click();
 await page.locator('[data-run][data-action=pause]').waitFor();
 await page.locator('[data-run][data-action=pause]').click();
 await page.locator('[data-run][data-action=resume]').waitFor();
 await page.getByRole('button',{name:'Connections',exact:true}).click();
 await page.getByLabel('Form (for form submissions)').selectOption({label:'Request an estimate'});
 await page.getByLabel('Enable connection for future events').check();
 await page.getByRole('button',{name:'Save connection',exact:true}).click();
 await page.getByRole('button',{name:'Offer email consent',exact:true}).click();
 await page.getByRole('button',{name:'Stop offering',exact:true}).waitFor();
 await page.getByRole('button',{name:'Templates',exact:true}).click();
 await mkdir('.artifacts/email',{recursive:true});
 await page.screenshot({path:'.artifacts/email/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'.artifacts/email/mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 assert.deepEqual(failures,[]);
 assert.equal(await page.locator('[data-error]').innerText(),'');
 console.log('Email browser workflow passed: edit, preview, publish, settings, consent, start, pause, connections, and mobile layout.');
}finally{await browser.close();}
